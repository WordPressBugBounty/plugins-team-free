<?php
/**
 * Registers editor and frontend assets for Smart Team Pro blocks.
 *
 * Responsible for registering script and style handles used by
 * Gutenberg blocks in both editor and frontend.
 *
 * @package ShapedPlugin\WPTeam\Blocks
 */

namespace ShapedPlugin\WPTeam\Blocks\Includes;

use ShapedPlugin\WPTeam\Admin\Dashboard\DashboardHelper;
use ShapedPlugin\WPTeam\Blocks\Includes\AI\AIFeature;
use ShapedPlugin\WPTeam\Blocks\Includes\AI\AIKeyManager;
use ShapedPlugin\WPTeam\Blocks\Includes\ReadyPatterns\PatternRepository;

defined( 'ABSPATH' ) || exit;

/**
 * Asset manager class.
 */
class AssetManager {

	/**
	 * Class instance.
	 *
	 * @var AssetManager|null
	 */
	private static $instance = null;
	/**
	 * Get class instance.
	 *
	 * Ensures only one instance of the class is loaded.
	 *
	 * @return AssetManager
	 */
	public static function instance() {
		if ( null === self::$instance ) {
			self::$instance = new self();
		}
		return self::$instance;
	}

	/**
	 * Get plugin root URL.
	 *
	 * @return string
	 */
	private function get_plugin_url() {
		return SPT_PLUGIN_ROOT;
	}

	/**
	 * Get plugin root path.
	 *
	 * @return string
	 */
	private function get_plugin_path() {
		return SPT_PLUGIN_PATH;
	}

	/**
	 * Register block editor assets.
	 *
	 * Registers editor JavaScript and CSS bundles generated by the build process.
	 * Also registers shared block styles used in both editor and frontend.
	 *
	 * @return void
	 */
	public function register_block_editor_assets() {
		if ( wp_script_is( 'sptp-blocks-editor', 'registered' ) ) {
			return;
		}

		$asset_file = $this->get_plugin_path() . 'dist/editor/index.asset.php';
		$deps       = array( 'wp-blocks', 'wp-block-editor', 'wp-components', 'wp-i18n', 'wp-element' );
		$version    = SPT_PLUGIN_VERSION;

		if ( file_exists( $asset_file ) ) {
			$asset = require $asset_file;
			if ( ! empty( $asset['dependencies'] ) && is_array( $asset['dependencies'] ) ) {
				$deps = $asset['dependencies'];
			}
			if ( ! empty( $asset['version'] ) ) {
				$version = $asset['version'];
			}
		}

		wp_register_script(
			'sptp-blocks-editor',
			$this->get_plugin_url() . 'dist/editor/index.js',
			$deps,
			$version,
			true
		);

		// Editor runtime config — lets the editor build asset URLs (e.g. the
		// Image Masking shape SVGs under blocks/assets/images/mask/ and the Pro
		// upgrade dialog's layout previews under blocks/assets/images/pro-upgrade/).
		wp_localize_script(
			'sptp-blocks-editor',
			'sptpBlocksEditor',
			array(
				'blocksUrl'     => SPT_BLOCKS_URL,
				// Admin base for editor deep links (AI Builder, Ready Patterns).
				'adminUrl'      => admin_url(),
				// Target of the demo-members notice's "Add Your Team Members" link.
				'newMemberUrl'  => admin_url( 'post-new.php?post_type=sptp_member' ),
				// Targets of the canvas "block is off" notice's link (inserterVisibility.js).
				'blocksPageUrl'  => admin_url( 'edit.php?post_type=sptp_member&page=sptp_dashboard#blocks' ),
				'modulesPageUrl' => admin_url( 'edit.php?post_type=sptp_member&page=sptp_dashboard#modules' ),
				// Dashboard → Blocks switches: the managed names and which of
				// them are effectively on, so the inserter and canvas gate
				// (inserterVisibility.js) follow the same rule as the frontend.
				'toggleManagedBlocks' => DashboardHelper::get_toggle_managed_block_names(),
				'activeBlockList'     => DashboardHelper::get_enabled_block_names(),
				// Dashboard → Modules: field blocks / Card Content rows whose
				// feature is off, resolved here so the maps stay in PHP.
				'moduleOffBlocks'     => DashboardHelper::get_module_disabled_block_names(),
				'moduleOffElements'   => DashboardHelper::get_module_disabled_card_elements(),
				// Ready Patterns library — the header launcher's on/off state
				// and its REST base. Pro also sends `pluginVersion` and
				// `modulesUrl` for its requirements preflight, which Free
				// does not ship.
				'readyPatterns' => array(
					'headerLauncher' => PatternRepository::is_header_launcher_enabled(),
					'restBase'       => PatternRepository::rest_base(),
				),
			)
		);

		// The Pro/Free gate payload — the editor twin (apps/blocks/shared/
		// proGate.js) reads this to hide Pro-only blocks from the inserter and
		// lock Pro-only card designs/elements in the free layout blocks'
		// inspectors. See blocks/Includes/Pro_Gate.php.
		wp_localize_script( 'sptp-blocks-editor', 'sptpProGate', Pro_Gate::localize() );

		wp_register_style(
			'sptp-blocks-editor',
			$this->get_plugin_url() . 'dist/editor/index.css',
			array(),
			$this->css_version( 'dist/editor/index.css', $version )
		);

		// Icon fonts for the social / meta icons. The block types declare Pro's
		// handle names (shared block layer), so register them here against
		// Free's own copies — legacy src/ registers the same files under
		// `team-free-fontawesome` / `sptp-fontello-icon`, which the blocks never
		// see. Runs on `init`, so the handles exist in the editor and frontend.
		if ( ! wp_style_is( 'sp_team_fontawesome', 'registered' ) ) {
			wp_register_style(
				'sp_team_fontawesome',
				$this->get_plugin_url() . 'src/Frontend/css/font-awesome.min.css',
				array(),
				SPT_PLUGIN_VERSION
			);
		}
		if ( ! wp_style_is( 'sp_team_fontello', 'registered' ) ) {
			wp_register_style(
				'sp_team_fontello',
				$this->get_plugin_url() . 'src/Admin/css/fontello.min.css',
				array(),
				SPT_PLUGIN_VERSION
			);
		}

		// Shared style bundle used by both editor and frontend.
		if ( file_exists( $this->get_plugin_path() . 'dist/editor/style-index.css' ) ) {
			wp_register_style(
				'sptp-blocks-style',
				$this->get_plugin_url() . 'dist/editor/style-index.css',
				array(),
				$this->css_version( 'dist/editor/style-index.css', $version )
			);
		}
	}

	/**
	 * Cache-busting version for a built stylesheet.
	 *
	 * The index.asset.php hash tracks the JS only, so a CSS-only build kept the old
	 * `?ver=` and CDNs (Cloudflare, 10-year max-age) kept serving the stale file.
	 *
	 * @param string $relative_path Path under the plugin root.
	 * @param string $fallback      Version used when the file can't be stat'd.
	 * @return string
	 */
	private function css_version( $relative_path, $fallback ) {
		$mtime = @filemtime( $this->get_plugin_path() . $relative_path ); // phpcs:ignore WordPress.PHP.NoSilencedErrors
		return $mtime ? $fallback . '.' . $mtime : $fallback;
	}

	/**
	 * Enqueue the WP core code editor (CodeMirror) on the block editor screen.
	 *
	 * Powers the shared SpCssCodeEditor used in every block's Advanced Settings →
	 * Advanced → Custom CSS field (replacing the former Monaco editor). Returns
	 * false when the user has disabled the code editor in their profile; the
	 * component then falls back to a plain textarea.
	 *
	 * Hooked on `enqueue_block_editor_assets` so CodeMirror's script + styles are
	 * present before `sptp-blocks-editor` runs.
	 *
	 * @return void
	 */
	public function enqueue_code_editor_assets() {
		if ( function_exists( 'wp_enqueue_code_editor' ) ) {
			wp_enqueue_code_editor( array( 'type' => 'text/css' ) );
		}
	}

	/**
	 * Localize the AI Team Builder payload for the editor.
	 *
	 * One flag folds the module toggle and the site's own AI support, so the
	 * editor offers exactly what sptp/v1/ai-generate serves. Keys never ride
	 * this payload, only whether a usable one exists. Hooked to the editor
	 * enqueue rather than `init` so key state is read on editor screens only.
	 *
	 * @return void
	 */
	public function localize_ai_builder() {
		$available = AIFeature::is_available();

		wp_localize_script(
			'sptp-blocks-editor',
			'sptpAIBuilder',
			$available
				? array(
					'enabled'     => true,
					'settings'    => $this->editor_ai_settings(),
					'settingsUrl' => admin_url( 'edit.php?post_type=sptp_member&page=sptp_dashboard#settings=ai' ),
				)
				: array( 'enabled' => false )
		);
	}

	/**
	 * The slice of the public AI settings the editor needs. Every user with
	 * `edit_posts` loads it, so it carries no key suffixes, verdict messages or
	 * other providers' state.
	 *
	 * @return array
	 */
	private function editor_ai_settings() {
		$settings = AIKeyManager::get_public_settings();
		$provider = $settings['provider'];

		return array(
			'provider'       => $provider,
			'has_key'        => $settings['has_key'],
			'key_status'     => $settings['key_status'],
			'ai_enabled'     => $settings['ai_enabled'],
			'connectors'     => array(
				$provider => array( 'registered' => ! empty( $settings['connectors'][ $provider ]['registered'] ) ),
			),
			'connectors_url' => $settings['connectors_url'],
			'providers'      => AIKeyManager::builder_providers(),
		);
	}

	/**
	 * Register frontend assets.
	 *
	 * Registers frontend-only scripts and styles required by blocks. The
	 * runtime is plain browser JS (no build step), enqueued by a block's
	 * render callback only when a feature needs it (e.g. Grid enqueues it
	 * when Ajax Pagination is on) — mirrors testimonial-pro's script.js.
	 *
	 * @return void
	 */
	public function register_frontend_assets() {
		if ( is_admin() || wp_script_is( 'sptp-blocks-frontend', 'registered' ) ) {
			return;
		}

		// The one vendored Swiper 12.2.0 bundle, shared with the classic
		// shortcode's `team-free-swiper` handle; its global is renamed SPTPSwiper
		// so another plugin's Swiper never collides with ours.
		wp_register_script(
			'sptp-swiper',
			SPT_PLUGIN_ROOT . 'src/Frontend/js/swiper.min.js',
			array(),
			'12.2.0',
			true
		);
		wp_register_style(
			'sptp-swiper',
			SPT_PLUGIN_ROOT . 'src/Frontend/css/swiper.min.css',
			array(),
			'12.2.0'
		);

		wp_register_script(
			'sptp-blocks-frontend',
			// Swap in the unminified build for debugging: SPT_BLOCKS_URL . 'assets/js/script.js'.
			SPT_BLOCKS_URL . 'assets/js/script.min.js',
			array(),
			SPT_PLUGIN_VERSION,
			true
		);

		wp_localize_script(
			'sptp-blocks-frontend',
			'sptp_localize_data',
			array(
				'ajaxUrl' => admin_url( 'admin-ajax.php' ),
				'nonce'   => wp_create_nonce( 'sptp_block_nonce' ),
			)
		);
	}
}
